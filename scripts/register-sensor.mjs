/**
 * Generates scripts/seed_sensor.sql: registers (or re-keys) an air quality
 * collector and one of its devices directly in D1, like create-admin-direct.mjs
 * does for the master admin. See docs/AIR-QUALITY-COLLECTOR.md, "Cadastro".
 *
 * Every run issues a NEW collector token. Only its SHA-256 hash goes into the
 * SQL; the token itself is written to the collector's .env (--write-env), or
 * printed once when that flag is absent. Re-running for the same collector
 * name rotates its token and keeps its id.
 *
 * Usage:
 *   node scripts/register-sensor.mjs \
 *     --collector bancada-hermes \
 *     --device ebdaebfb3e5ed2f01crg1m --vendor tuya --model "BREATHE BTL40001" \
 *     --label "Airmonitor 01" \
 *     [--space-model "Sala 09" | --space <space-id>] \
 *     [--write-env collector/.env]
 *   npx wrangler d1 execute ufcim-db-dev --local --env dev --file=scripts/seed_sensor.sql
 *
 * ⚠️  The generated SQL is gitignored. The token never appears in it.
 */

import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const { values: args } = parseArgs({
  options: {
    collector: { type: 'string' },
    device: { type: 'string' },
    vendor: { type: 'string', default: 'tuya' },
    model: { type: 'string', default: 'BREATHE BTL40001' },
    label: { type: 'string' },
    space: { type: 'string' },
    'space-model': { type: 'string' },
    'write-env': { type: 'string' },
  },
});

if (!args.collector || !args.device) {
  console.error('Uso: --collector <nome> --device <external-id> [--label …] [--space-model … | --space …] [--write-env collector/.env]');
  process.exit(1);
}
if (args.space && args['space-model']) {
  console.error('Use --space ou --space-model, não os dois.');
  process.exit(1);
}

const sql = (value) => (value === undefined || value === null ? 'NULL' : `'${String(value).replaceAll("'", "''")}'`);

async function sha256Hex(input) {
  const digest = await crypto.subtle.digest('SHA-256', new TextEncoder().encode(input));
  return [...new Uint8Array(digest)].map((b) => b.toString(16).padStart(2, '0')).join('');
}

// 32 random bytes, base64url — same strength as generateOpaqueToken().
const tokenBytes = crypto.getRandomValues(new Uint8Array(32));
const token = Buffer.from(tokenBytes).toString('base64url');
const tokenHash = await sha256Hex(token);
const now = new Date().toISOString();
const collectorId = crypto.randomUUID();
const deviceId = crypto.randomUUID();

const spaceExpr = args.space
  ? sql(args.space)
  : args['space-model']
    ? `(SELECT id FROM spaces WHERE model_id = ${sql(args['space-model'])})`
    : 'NULL';
const collectorExpr = `(SELECT id FROM sensor_collectors WHERE name = ${sql(args.collector)})`;

const statements = [
  `-- Generated by scripts/register-sensor.mjs at ${now}. Gitignored.`,
  `INSERT INTO sensor_collectors (id, name, token_hash, created_at, updated_at)
  SELECT ${sql(collectorId)}, ${sql(args.collector)}, ${sql(tokenHash)}, ${sql(now)}, ${sql(now)}
  WHERE NOT EXISTS (SELECT 1 FROM sensor_collectors WHERE name = ${sql(args.collector)});`,
  `UPDATE sensor_collectors SET token_hash = ${sql(tokenHash)}, revoked_at = NULL, updated_at = ${sql(now)}
  WHERE name = ${sql(args.collector)};`,
  `INSERT INTO sensor_devices (id, external_id, vendor, model, label, collector_id, space_id, created_at, updated_at)
  VALUES (${sql(deviceId)}, ${sql(args.device)}, ${sql(args.vendor)}, ${sql(args.model)}, ${sql(args.label)},
          ${collectorExpr}, ${spaceExpr}, ${sql(now)}, ${sql(now)})
  ON CONFLICT (external_id) DO UPDATE SET
    vendor = excluded.vendor, model = excluded.model, label = excluded.label,
    collector_id = excluded.collector_id, space_id = excluded.space_id,
    retired_at = NULL, updated_at = excluded.updated_at;`,
];

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, 'seed_sensor.sql');
await writeFile(outPath, statements.join('\n\n') + '\n', 'utf8');
console.log(`SQL gravado em ${outPath}`);

if (args['write-env']) {
  const envPath = resolve(args['write-env']);
  const current = existsSync(envPath) ? await readFile(envPath, 'utf8') : '';
  const line = `UFCIM_COLLECTOR_TOKEN=${token}`;
  const next = /^UFCIM_COLLECTOR_TOKEN=.*$/m.test(current)
    ? current.replace(/^UFCIM_COLLECTOR_TOKEN=.*$/m, line)
    : `${current.trimEnd()}\n${line}\n`;
  await writeFile(envPath, next, { encoding: 'utf8', mode: 0o600 });
  console.log(`Token do coletor "${args.collector}" gravado em ${envPath} (não impresso).`);
} else {
  console.log(`Token do coletor "${args.collector}" (guarde agora, não será mostrado de novo):\n${token}`);
}
